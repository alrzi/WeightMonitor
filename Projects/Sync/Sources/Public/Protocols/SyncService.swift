import Foundation

public protocol SyncService: Sendable {
    /// Запускает приём входящих событий и первичную синхронизацию.
    ///
    /// Повторные вызовы не должны создавать дополнительные циклы обработки.
    nonisolated func start()

    /// Сигнализирует сервису, что исходящую очередь нужно проверить и отправить.
    ///
    /// Метод не ожидает завершения отправки. Несколько близких запросов могут быть
    /// объединены сервисом в один проход по очереди.
    nonisolated func requestFlush()
}
